import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');
// Character art: whale-girl sprite sheets sliced by tools/prepare-whale-girl.py.
const spriteManifest = JSON.parse(read('assets/sprites/manifest.json'));
const assets = {};
let frameCount = 0, spriteBytes = 0;
for (const [state, sprite] of Object.entries(spriteManifest.states)) {
  const frames = sprite.frames.map(file => {
    const bytes = fs.readFileSync(path.join(root, 'assets/sprites', file));
    if (bytes.subarray(0, 8).toString('latin1') !== '\x89PNG\r\n\x1a\n') throw new Error(`Unsafe sprite: ${file}`);
    const width = bytes.readUInt32BE(16), height = bytes.readUInt32BE(20);
    if (width < 32 || height < 32 || width > 1024 || height > 1024) throw new Error(`Unexpected sprite size: ${file} ${width}x${height}`);
    frameCount++; spriteBytes += bytes.length;
    return `data:image/png;base64,${bytes.toString('base64')}`;
  });
  if (!frames.length || frames.length !== sprite.count) throw new Error(`Sprite frames disagree with the manifest: ${state}`);
  assets[state] = { frames, fps: sprite.fps, playback: sprite.playback, ...(sprite.frameMs ? { frameMs: sprite.frameMs } : {}) };
}
if (['working', 'celebrate', 'waiting', 'resting', 'sleeping', 'error'].some(state => !assets[state])) throw new Error('Missing sprite states');
if (spriteBytes > 3 * 1024 * 1024) throw new Error(`Sprite budget exceeded: ${spriteBytes} bytes`);
const character = spriteManifest.character;
const bubbleFonts = {};
for (const language of ['en', 'zh']) {
  const bytes = fs.readFileSync(path.join(root, `assets/fonts/bubble-${language}.woff2`));
  if (bytes.toString('ascii', 0, 4) !== 'wOF2') throw new Error(`Invalid embedded font: ${language}`);
  bubbleFonts[language] = `data:font/woff2;base64,${bytes.toString('base64')}`;
}
const fontLoader = read('src/fonts.js').replace(/^export /gm, '');
const bubblePosition = read('src/bubble-layout.js').replace(/^export /gm, '');
const bubbleSurface = read('src/bubble-surface.js').replace(/^export /gm, '');
const css = read('src/pet.css');
const i18n = read('src/i18n.js').replace(/^export /gm, '');
const state = read('src/state.js').replace(/^export /gm, '');
const globalState = read('src/global-state.js').replace(/^import .*;\n/gm, '').replace(/^export /gm, '');
const sessionList = read('src/session-list.js').replace(/^import .*;\n/gm, '').replace(/^export /gm, '');
const workspaceReveal = read('src/workspace-reveal.js').replace(/^import .*;\n/gm, '').replace(/^export /gm, '');
const spriteLogic = read('src/sprites.js').replace(/^import .*;\n/gm, '').replace(/^export /gm, '');
const widget = read('src/widget.js').replace(/^import .*;\n/gm, '').replace(/^export /gm, '');
const adapter = read('src/adapter.js').replace(/^import .*;\n/gm, '').replace(/^export /gm, '');
const common = `const ASSETS=${JSON.stringify(assets)};\nconst SPRITES=${JSON.stringify(character)};\nconst CSS=${JSON.stringify(css)};\nconst BUBBLE_FONTS=${JSON.stringify(bubbleFonts)};\n${i18n}\n${state}\n${globalState}\n${sessionList}\n${workspaceReveal}\n${spriteLogic}\n${fontLoader}\n${bubblePosition}\n${bubbleSurface}\n${widget}\n`;
fs.mkdirSync(path.join(root, 'lib'), { recursive: true });
const bridge = read('src/bridge-client.js').replace(/^import .*;\n/gm, '').replace(/^export /gm, '');
const remote = read('lib/remote.js');
const exportsBlock = /\nexport \{([^}]+)\};?\s*$/;
const expectedExports = ['TYPERT_REMOTE', 'WHALE_FRAME_SCHEMA', 'WHALE_WATCH_DESCRIPTOR'];
const exportedNames = remote.match(exportsBlock)?.[1].split(',').map(name => name.trim()).filter(Boolean).sort();
if (JSON.stringify(exportedNames) !== JSON.stringify(expectedExports)) throw new Error('Unexpected bridge contract exports; refusing a broken bundle');
const contract = `const WhaleBridgeContract=(()=>{${remote.replace(exportsBlock, '')}\nreturn {${expectedExports.join(',')}};})();`;
fs.writeFileSync(path.join(root, 'lib/index.js'), read('src/host-bridge.js'));
fs.writeFileSync(path.join(root, 'lib/client.js'), `// Generated by tools/build.mjs. Uses the existing authenticated DSH connection only.\nwindow.__ModuleLoader__.load({id:'dsh-plugin-whale-girl',factory:function(require){\n'use strict';\n${common}\n${contract}\n${bridge}\n${adapter}\nreturn createPlugin(require, ASSETS, CSS, BUBBLE_FONTS, SPRITES);\n}});\n`);
console.log(`Built client bundle; validated ${frameCount} sprite frames across ${Object.keys(assets).length} states (${Math.round(spriteBytes / 1024)} KiB).`);
